// School-day attendance (backend: /academics/attendance/daily, /settings, /calendar)

export type DailyStatus = 'present' | 'late' | 'absent' | 'excused' | 'sick' | 'tardy';
export type ManualDailyStatus = Exclude<DailyStatus, 'tardy'>;
export type AttendanceSource = 'qr' | 'manual' | 'auto';
export type ExcuseStatus = 'pending' | 'approved' | 'rejected';

export interface DailyAttendanceRecord {
  id: string;
  student_id: string;
  class_id: string;
  academic_year_id: string;
  date: string;
  status: DailyStatus;
  source: AttendanceSource;
  check_in_at?: string | null;
  check_out_at?: string | null;
  marked_by?: string | null;
  marked_at: string;
  excuse_reason?: string | null;
  excuse_status?: ExcuseStatus | null;
  excuse_document_url?: string | null;
  excuse_reviewed_by?: string | null;
  notes?: string | null;
}

export interface SchoolDayInfo {
  date: string;
  is_school_day: boolean;
  reason?: string | null;
  today: string; // school-local today
  auto_absent_applied: boolean;
}

export interface DailyRosterEntry {
  student_id: string;
  student_name: string;
  admission_number?: string | null;
  photo?: string | null;
  record: DailyAttendanceRecord | null; // null = not marked yet
}

export interface DailyRoster {
  class_id: string;
  class_name?: string | null;
  day: SchoolDayInfo;
  entries: DailyRosterEntry[];
}

export interface DailyStatusInput {
  status: ManualDailyStatus;
  notes?: string;
  excuse_reason?: string; // required when status is 'excused'
  excuse_document_url?: string;
}

export interface DailyBulkInput {
  class_id: string;
  date?: string;
  entries: Array<DailyStatusInput & { student_id: string }>;
}

export interface AttendanceSettings {
  timezone: string;
  school_days: number[]; // 0 = Monday … 6 = Sunday
  late_after: string;     // "HH:MM:SS"
  scan_closes_at: string;
  auto_absent_at: string;
  allow_checkout_scan: boolean;
}

export interface SchoolCalendarDay {
  date: string;
  is_school_day: boolean;
  label?: string | null;
}

export interface DailyAttendanceSummary {
  school_days: number;
  present: number;
  late: number;
  absent: number;
  excused: number;
  sick: number;
  attendance_rate: number | null; // null when every record is excused/sick
}

export interface StudentDailyHistory {
  student_id: string;
  student_name?: string | null;
  admission_number?: string | null;
  start_date: string;
  end_date: string;
  summary: DailyAttendanceSummary;
  records: DailyAttendanceRecord[];
}

export interface AttendanceEvent {
  id: string;
  event_type: 'scan_accepted' | 'scan_duplicate' | 'scan_rejected' | 'manual_set' | 'excuse_set' | 'excuse_reviewed' | 'auto_absent';
  old_status?: string | null;
  new_status?: string | null;
  actor_id?: string | null;
  actor_name?: string | null;
  device_label?: string | null;
  reason?: string | null;
  occurred_at: string;
}

// QR ID-card scanning (backend: /academics/attendance/scan, /id-cards)

export type ScanMode = 'check_in' | 'check_out';
export type ScanRejectReason =
  | 'invalid_signature' | 'wrong_tenant' | 'unknown_student' | 'revoked' | 'inactive_student'
  | 'not_school_day' | 'scan_closed' | 'scan_expired' | 'not_enrolled' | 'not_your_class'
  | 'checkout_disabled' | 'not_checked_in';

/** The offline queue's fields on a scan (phase6-design.md section 8): sent with every scan. */
export interface QueuedScanFields {
  /** When the card was read, ISO 8601 with offset (counts only today, not future, <= 12 h old) */
  scanned_at?: string;
  /** 1-64 characters; sending it again returns the first outcome */
  client_scan_id?: string;
}

export interface ScannedStudent {
  id: string;
  name: string;
  admission_number?: string | null;
  photo?: string | null;
  class_name?: string | null;
}

export interface ScanResult {
  result: 'accepted' | 'duplicate' | 'rejected';
  reason?: ScanRejectReason | null;
  mode: ScanMode;
  student?: ScannedStudent | null;
  status?: DailyStatus | null;
  check_in_at?: string | null;
  check_out_at?: string | null;
}

export interface IdCard {
  student_id: string;
  student_name: string;
  admission_number?: string | null;
  photo?: string | null;
  class_name?: string | null;
  academic_year?: string | null;
  card_version: number;
  card_issued_at?: string | null;
  qr_svg: string; // inline SVG markup generated by the server
}

// Excuses (documents, parent submissions, review queue)

export interface ExcuseDocument {
  filename: string;
  content_type: string; // image/jpeg | image/png | image/webp | application/pdf
  data_base64: string;
  size_bytes?: number;
}

export interface ParentExcuseInput {
  student_id: string;
  date: string;
  reason: string;
  document?: ExcuseDocument;
}

export interface ExcuseListItem {
  daily_id: string;
  student_id: string;
  student_name: string;
  class_name?: string | null;
  date: string;
  status: DailyStatus;
  excuse_status?: ExcuseStatus | null;
  excuse_reason?: string | null;
  has_document: boolean;
  submitted_by_name?: string | null;
  submitted_at: string;
}

export interface ChildSummary {
  student_id: string;
  name: string;
  admission_number?: string | null;
  class_name?: string | null;
}

// Reporting

export interface AttendanceCounts {
  enrolled: number;     // class report totals: student-days
  present: number;      // includes tardy
  late: number;
  absent: number;
  excused: number;
  sick: number;
  unmarked: number;
  scanned: number;      // checked in by QR card
  attendance_rate: number | null;
}

export interface ClassOverview extends AttendanceCounts {
  class_id: string;
  class_name?: string | null;
  sponsor_name?: string | null;
}

export interface DailyOverview {
  day: SchoolDayInfo;
  totals: AttendanceCounts;
  classes: ClassOverview[];
  pending_excuses: number;
}

export interface StudentReportRow {
  student_id: string;
  student_name: string;
  admission_number?: string | null;
  present: number;
  late: number;
  absent: number;
  excused: number;
  sick: number;
  unmarked: number;
  attendance_rate: number | null;
}

export interface ClassAttendanceReport {
  class_id: string;
  class_name?: string | null;
  start_date: string;
  end_date: string;
  school_days: number;
  rows: StudentReportRow[];
  totals: AttendanceCounts;
}
